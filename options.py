from bpy.props import BoolProperty, EnumProperty, StringProperty


def mesh_pose(default):
    return EnumProperty(
        name="Mesh Pose",
        items=(
            ("CAPTURED", "Captured Pose", "Use the skinned vertex positions from this frame"),
            ("PRE_SKINNING", "Pre-Skinning", "Use the positions supplied to the skinning shader"),
        ),
        default=default,
    )


class ImportOptions:
    pose: mesh_pose("CAPTURED")
    draw_filter: StringProperty(
        name="Draw Calls / IB Hashes",
        description="Import selected draw numbers or eight-digit index-buffer hashes, separated by commas",
    )
    import_weights: BoolProperty(
        name="Vertex Groups", description="Import weights using the component's bone palette indices", default=True,
    )
    import_textures: BoolProperty(
        name="Textures", description="Load DDS textures bound to each component's pixel shader", default=True,
    )
    pack_textures: BoolProperty(
        name="Pack Textures", description="Embed loaded textures when saving the Blender file", default=False,
    )
    include_without_uv: BoolProperty(
        name="Include Draws Without UVs", description="Include skinned geometry from passes without surface UVs",
        default=False,
    )


class ExportOptions:
    dds_folder: StringProperty(
        name="DDS Replacement Folder",
        description="Folder containing replacement DDS files named by the original texture hash",
        subtype="DIR_PATH",
    )
    overwrite: BoolProperty(
        name="Overwrite APMI Export",
        description="Replace an existing folder generated by APMI-Tools",
        default=False,
    )


def draw_import_options(layout, settings):
    layout.prop(settings, "draw_filter")
    layout.prop(settings, "import_weights")
    layout.prop(settings, "import_textures")
    row = layout.row()
    row.enabled = settings.import_textures
    row.prop(settings, "pack_textures")
    layout.prop(settings, "include_without_uv")


def draw_export_options(layout, settings):
    layout.prop(settings, "dds_folder")
    layout.prop(settings, "overwrite")
